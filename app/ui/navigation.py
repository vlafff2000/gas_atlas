PAGES=['Обзор','Импорт данных','Производительность скважин','Гистограммы по эксплуатации скважин','ГДИ','Графики реагирования','Кроссплот давлений','Поскважинный анализ','Аналитика фонда','Группы','Экспорт','Исключенные точки','История фильтра','Паспорт скважины','Проекты','Настройки']
DEFAULT=['Импорт данных','Производительность скважин','Гистограммы по эксплуатации скважин','ГДИ','Графики реагирования','Кроссплот давлений','Группы','Экспорт','Настройки']
ALIASES={'Адаптация модели давлений':'Кроссплот давлений','Динамика':'Производительность скважин','Реагирование':'Графики реагирования'}

def visible(settings):
    chosen=[ALIASES.get(x,x) for x in settings.get('visible_pages',DEFAULT)]
    if not settings.get('pressure_module_menu_seen'):chosen.append('Кроссплот давлений')
    return [p for p in PAGES if p in chosen or p=='Настройки']
