"""Состав меню: имена разделов хранятся в настройке проекта ``visible_pages`` (старые имена 5.8 — через ``ALIASES``)."""
PAGES = ['Обзор', 'Импорт данных', 'Производительность скважин', 'Вынос воды и водный фактор', 'Гистограммы по эксплуатации скважин',
         'БД по учету газа', 'Сравнение БД ЭЛПРО', 'Суточный график ЭЛПРО', 'План и факт по группам',
         'Газодинамические исследования', 'Динамика коэффициентов ГДИ', 'ГГХ', 'Графики реагирования', 'Кроссплот давлений',
         'Поскважинный анализ', 'Аналитика фонда', 'Группы', 'Авторский надзор: сезон', 'Авторский надзор: ревизия КРУ',
         'Проверка данных', 'Экспорт', 'Исключенные точки', 'История фильтра', 'Паспорт скважины', 'Проекты', 'Настройки']
DEFAULT = ['Производительность скважин', 'Вынос воды и водный фактор', 'Газодинамические исследования', 'ГГХ',
           'Графики реагирования', 'Экспорт', 'Настройки']
ALIASES = {'Адаптация модели давлений': 'Кроссплот давлений', 'Динамика': 'Производительность скважин',
           'Реагирование': 'Графики реагирования', 'ГДИ': 'Газодинамические исследования'}
ALWAYS = ('Импорт данных', 'Настройки')      # скрыть нельзя: без импорта и настроек проект не наполнить

def visible(settings):
    saved = 'visible_pages' in settings and settings['visible_pages'] is not None
    chosen = [ALIASES.get(x, x) for x in (settings['visible_pages'] if saved else DEFAULT)]
    if saved and not settings.get('pressure_module_menu_seen'):chosen.append('Кроссплот давлений')    # проекты 5.8 до появления «Кроссплота»
    return [p for p in PAGES if p in chosen or p in ALWAYS]
